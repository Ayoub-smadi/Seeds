export function useTranslation() {
  const { lang } = useAppStore();
  
  const t = (key: keyof typeof translations.en): string => {
    return (translations[lang] as Record<string, string>)[key] || (translations.en as Record<string, string>)[key] || key;
  };

  return { t, lang };
}
